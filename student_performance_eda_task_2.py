import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

print("Libraries imported successfully!")

url = "https://raw.githubusercontent.com/6303628755/student-data-cleaning-2026/main/cleaned_student_data.csv"

df = pd.read_csv(url)

print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)

display(df.head())

print("Dataset Information:")
df.info()

print("\nColumn Names:")
print(df.columns.tolist())

print("\nMissing Values:")
display(df.isnull().sum())

print("\nDuplicate Rows:")
print(df.duplicated().sum())

print("Statistical Summary:")

display(df.describe().T)

print("\nAverage GPA:")
print(round(df["GPA"].mean(), 2))

print("\nMedian GPA:")
print(round(df["GPA"].median(), 2))

print("\nAverage Weekly Study Time:")
print(round(df["StudyTimeWeekly"].mean(), 2))

print("\nAverage Absences:")
print(round(df["Absences"].mean(), 2))

plt.figure(figsize=(8, 5))

sns.histplot(data=df, x="GPA", bins=20, kde=True)

plt.title("Distribution of Student GPA")
plt.xlabel("GPA")
plt.ylabel("Number of Students")

plt.show()

plt.figure(figsize=(8, 5))

sns.countplot(data=df, x="GradeClass")

plt.title("Student Count by Grade Class")
plt.xlabel("Grade Class")
plt.ylabel("Number of Students")

plt.show()

plt.figure(figsize=(8, 5))

sns.scatterplot(
    data=df,
    x="StudyTimeWeekly",
    y="GPA"
)

plt.title("Weekly Study Time vs GPA")
plt.xlabel("Weekly Study Time (Hours)")
plt.ylabel("GPA")

plt.show()

plt.figure(figsize=(8, 5))

sns.scatterplot(
    data=df,
    x="Absences",
    y="GPA"
)

plt.title("Absences vs GPA")
plt.xlabel("Number of Absences")
plt.ylabel("GPA")

plt.show()

plt.figure(figsize=(8, 5))

sns.boxplot(data=df, x="Tutoring", y="GPA")

plt.title("GPA by Tutoring Status")
plt.xlabel("Tutoring Status")
plt.ylabel("GPA")

plt.show()

print("===== 5 DATA ANALYSIS INSIGHTS =====")

print("\n1. Dataset Size:")
print("Total students:", df.shape[0])
print("Total columns:", df.shape[1])

print("\n2. Missing Values:")
print(df.isnull().sum().sum(), "missing values found")

print("\n3. Duplicate Records:")
print(df.duplicated().sum(), "duplicate rows found")

print("\n4. Numerical Column Averages:")
display(df.select_dtypes(include="number").mean().round(2))

print("\n5. Highest and Lowest Values:")
display(df.select_dtypes(include="number").agg(["min", "max"]).T)

# Save statistical summary
summary = df.describe(include="all").T
summary.to_csv("eda_summary.csv")

# Save correlation matrix for numerical columns
correlation = df.select_dtypes(include="number").corr()
correlation.to_csv("correlation_matrix.csv")

print("EDA summary saved successfully!")
print("Correlation matrix saved successfully!")

